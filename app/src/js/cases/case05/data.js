function salimHint(g) {
  const has = id => g.has(id);
  const say = t => [['npc', t]];
  if (!has('st_salim_case')) return say('اسألني أولًا لماذا كانوا متأكدين من مصطفى. افهم القضية القديمة قبل أن تهدمها.');
  if (!has('ev_file')) return say('الملف في الصندوق على الكاونتر. ابدأ بالمحضر.');
  if (!has('ev_fathi2014')) return say('في آخر الملف ورقتان مدبستان. أقوال حارس الشارع.');
  if (!has('ev_photo')) return say('صورة مسرح الجريمة في الملف. انظر إليها طويلًا. الصور تحفظ ما ينساه الناس.');
  if (!has('ev_register')) return say('د. ريم وضعت الدفتر الذي وجدته على طاولة المعمل في المخزن الخلفي.');
  if (!has('ev_phone2014')) return say('سجل مكالمات الصيدلية في الملف. فؤاد اتصل بأحد قبل موته بربع ساعة.');
  if (!has('dd_alive_after')) return say('متى خرج مصطفى؟ ومتى كان فؤاد ما زال حيًا يصرخ؟ ضعهما جنبًا إلى جنب على اللوحة.');
  if (has('st_nahed_call') && !has('dd_call')) return say('ناهد تقول إن فؤاد كلمها ليقول إنه سيتأخر. قارن ذلك بما سمعه عم فتحي من خلف الصاج.');
  if (!has('ev_wallphoto')) return say('على الجدار الغربي صورة قديمة للصيدلية. انظر من يقف فيها، وبجانب ماذا.');
  if (!has('ev_badge')) return say('سترة عم فتحي على المشجب عند الباب. اقرأ ما على صدرها.');
  if (has('ev_badge') && !has('st_fathi_truth')) return say('عم فتحي يعمل عند من؟ ومنذ متى؟ واجهه بهذا.');
  if (!has('ev_mortar')) return say('الأداة لم يُعثر عليها في 2014. ربما لأنهم لم ينظروا إلى الرف.');
  if (!has('st_nahed_truth')) return say('ناهد تخفي شيئًا عن تلك المكالمة. حين تثبت لها أنها لم تكن المقصودة بها، ستتكلم.');
  if (Object.keys(g.cs.deductions).length < 7) return say('اربط الخيوط على اللوحة. مصطفى بريء أم لا؟ ومن غيره كان يملك مفتاحًا وسيارة وسببًا؟');
  return say('حين تكون مستعدًا، قل لي من قتل د. فؤاد. هذه المرة يجب أن نكون على حق.');
}

