function salimHint(g) {
  const has = id => g.has(id);
  const say = t => [['npc', t]];
  if (!has('st_salim_sms')) return say('اسألني عن زوجته أولًا. ما قالته لي على الهاتف أقلقني.');
  if (!has('ev_jacket')) return say('ابدأ بمكتب سامي نفسه. الناس يتركون وراءهم أكثر مما يظنون.');
  if (!has('st_hisham_left')) return say('المدير المالي يقول إنه آخر من رأى سامي. اسمع روايته.');
  if (!has('ev_computer')) return say('حاسوب سامي ما زال مفتوحًا. لم يغلقه أحد منذ الظهر.');
  if (has('ev_missed') && !has('st_noha_truth')) return say('الهاتف على مكتب الاستقبال رنّ ولم يرد أحد... ونهى تقول إنها لم تتحرك من مكانها.');
  if (!has('ev_missed')) return say('نهى تقسم إنها لم تترك مكتبها. انظر حول مكتب الاستقبال، الآلات لا تكذب.');
  if (!has('ev_mug')) return say('على مكتب سامي كوب قهوة. عم صابر قال لي إن سامي لا يشرب إلا الشاي الأخضر.');
  if (has('ev_interview') && !has('st_tarek_truth')) return say('طارق يخفي شيئًا عن ساعة الغداء. واجهه بما وجدته.');
  if (!has('ev_shredder')) return say('غرفة التصوير في آخر الصالة. أحدهم استعمل آلة التمزيق اليوم أكثر من المعتاد.');
  if (!has('ev_keylog')) return say('نهى تسجل كل مفتاح يخرج من اللوحة خلفها. ألقِ نظرة.');
  if (!has('st_saber_elevator')) return say('عم صابر يقضي يومه في المطبخ، بجوار مصعد الخدمة. أظنه رأى أكثر مما قال. ربما يتكلم إن عرف أنك تعرف.');
  if (!g.flag('hisham_refused')) return say('درج مكتب هشام مقفل. اطلب منه أن يفتحه، ولنرَ رد فعله.');
  if (!g.flag('warrant')) return say('إن أردت إذن تفتيش لمكتب هشام، أحضر لي ما يثبت أنه كذب علينا. ثم اطلبه مني.');
  if (!has('ev_hisham_drawer')) return say('الإذن معك. الدرج المقفل في مكتب هشام ينتظرك.');
  if (Object.keys(g.cs.deductions).length < 4) return say('علّق ما لديك على لوحة التحقيق واربط الخيوط. ما زالت هناك صلات لم ترها.');
  return say('سامي ربما ما زال في هذا المبنى، وربما يحتاج إلى مساعدة. حين تكون مستعدًا، أخبرني باستنتاجك.');
}

