function salimHint(g) {
  const has = id => g.has(id);
  const say = t => [['npc', t]];
  if (!has('st_salim_found')) return say('اسألني أولًا كيف وجدوه. التفاصيل الصغيرة مهمة.');
  if (!has('ev_tray')) return say('ابدأ بالغرفة 309 نفسها. الصينية ما زالت على الطاولة.');
  if (!has('ev_keylog')) return say('سجل البطاقات على حاسوب محطة الخدمة في الممر. كل باب فُتح من الخارج مسجل.');
  if (!has('ev_slip')) return say('تحت الإبريق ورقة صفراء. النادل يترك نسخة للنزيل دائمًا.');
  if (has('ev_slip') && !has('st_adel_truth')) return say('الإيصال يقول شيئًا، والنادل يقول شيئًا آخر. واجهه.');
  if (has('st_nadine_saw') && !has('st_nadine_truth')) return say('نادين متأكدة جدًا مما رأته. غرفتها مفتوحة، انظر كيف كانت ترى الليلة.');
  if (has('st_hazem_room') && !has('st_hazem_truth')) return say('حازم يقول إنه نام مبكرًا. غرفته 308 مفتوحة، ألقِ نظرة.');
  if (!has('st_rehab_truth')) return say('البطاقة الرئيسية فتحت 309 الساعة 10:48. رحاب تقول إن عربتها لم تفارق عينها. سلم الخدمة في آخر الممر.');
  if (!g.flag('r307_open')) return say('غرفة شريف 307 تحتاج موافقته. اطلبها منه.');
  if (!has('ev_pills') || !has('ev_shirt')) return say('غرفة 307 مفتوحة الآن. فتشها جيدًا، حتى سلة المهملات.');
  if (!has('ev_case')) return say('الحقيبة لم تخرج من المبنى. ونادين تقول إن الرجل اتجه نحو المصعد. ماذا هناك غير المصعد؟');
  if (Object.keys(g.cs.deductions).length < 6) return say('علّق ما لديك على اللوحة. الشاي، البطاقة، والحقيبة: ثلاثة خيوط ويد واحدة.');
  return say('كمال سيفيق صباحًا. حين تكون مستعدًا، قل لي من فعلها.');
}

