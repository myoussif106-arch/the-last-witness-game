function salimHint(g) {
  const has = id => g.has(id);
  const rubbed = g.cs.evidence.ev_notepad && g.cs.evidence.ev_notepad.details.includes('rubbed');
  const say = t => [['npc', t]];
  if (!has('ev_lock')) return say('ابدأ بالباب. إن لم يُكسر، فالسؤال: من فتحه؟');
  if (!has('st_hassan_keys')) return say('اسأل الأستاذ حسن عمّن يملك مفاتيح الشقة.');
  if (!has('ev_print')) return say('غرفة المكتب... لم أدخلها، لكن أرضيتها بدت لي مبللة من الباب.');
  if (has('ev_ashtray') && !has('st_nader_visit')) return say('عقب السيجارة في الصالة... الأستاذ حسن لا يدخن. فمن كان هنا اليوم؟');
  if (has('ev_fridge') && !has('st_mona_truth')) return say('ورقة منى على الثلاجة تقول شيئًا يختلف عمّا قالته لك. واجهها بها.');
  if (!g.flag('toolbox_allowed')) return say('كريم لم يبتعد عن صندوق عدته منذ وصلنا. ربما تستأذنه في نظرة.');
  if (has('ev_notepad') && !rubbed) return say('الورقة البيضاء على المكتب... الناس يضغطون بأقلامهم أكثر مما يظنون.');
  if (!has('ev_notepad')) return say('المكتب فيه أوراق الأستاذ حسن. الرجل كان يكتب كثيرًا كما قالت منى.');
  if (!has('ev_cabinet')) return say('الباب الرئيسي مقفل منذ التاسعة. لو كنت لصًا من داخل العمارة وسمعت سيارة الشرطة... أين أخبئ ما سرقته على عجل؟');
  if (!has('ev_trash')) return say('رائحة دخان على البسطة منذ وصلت. هل لاحظتها؟');
  if (Object.keys(g.cs.deductions).length < 3) return say('علّق ما لديك على لوحة التحقيق واربط بين الأشياء. التناقضات تظهر حين ترى الخيوط معًا.');
  return say('أظن أن لديك ما يكفي. حين تكون مستعدًا، أخبرني باستنتاجك.');
}

